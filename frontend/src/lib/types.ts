export type RoomType = "couple" | "double_bed";

export type RoomSummary = {
  id: number;
  slug: string;
  name: string;
  room_type: RoomType | null;
  room_type_label: string | null;
  description: string | null;
  max_adults: number;
  max_children: number;
  view: string | null;
  tour_360_url: string | null;
  featured_image: string | null;
  starting_price: number | null;
  currency: string;
  amenities: { slug: string; name: string }[];
  images: { path: string; alt: string | null }[];
  inventory?: number;
};

export type Offer = {
  id: number;
  slug: string;
  name_en: string;
  name_bn?: string | null;
  description_en?: string | null;
  description_bn?: string | null;
  discount_type?: string;
  discount_value?: number;
  image?: string | null;
};

export type Testimonial = {
  id: number;
  guest_name: string;
  quote_en: string;
  quote_bn?: string | null;
};

export type AvailabilityResult = {
  check_in: string;
  check_out: string;
  rooms: {
    id: number;
    slug: string;
    name: string;
    room_type: RoomType | null;
    room_type_label: string | null;
    max_adults: number;
    max_children?: number;
    available_rooms: number;
    /** Free physical rooms for the dates, regardless of the requested guest count. */
    units_available: number;
    starting_price?: number | null;
    fits_guests: boolean;
    quote: Quote | null;
  }[];
};

export type QuoteItem = {
  room_category_id: number;
  name: string;
  room_type: RoomType | null;
  room_type_label: string | null;
  max_adults: number;
  max_children: number;
  quantity: number;
  nights: number;
  nightly_rate: number;
  per_room_total: number;
  subtotal: number;
};

export type Quote = {
  items?: QuoteItem[];
  nights: number;
  nightly_rate?: number;
  room_count?: number;
  room_subtotal: number;
  meal_total: number;
  addon_total: number;
  discount_total: number;
  grand_total: number;
  advance_percent: number;
  advance_amount: number;
  balance_amount: number;
  currency: string;
};

export type BookingStatus =
  | "pending_confirmation"
  | "pending"
  | "paid"
  | "confirmed"
  | "checked_in"
  | "completed"
  | "cancelled"
  | "refunded"
  | "payment_failed"
  | "expired";

export type BookingPayload = {
  booking_number: string;
  /** Secret needed to read this booking back from the API. */
  access_token: string;
  status: BookingStatus;
  status_label: string;
  check_in: string;
  check_out: string;
  adults: number;
  children: number;
  room: string | null;
  room_count?: number;
  rooms?: BookingRoomLine[];
  nights?: number;
  room_subtotal?: number;
  meal_plan: string | null;
  addons: { name: string | null; quantity: number; total: number }[];
  special_requests: string | null;
  guest: { full_name: string; phone: string; whatsapp?: string | null; email?: string | null } | null;
  grand_total: number;
  advance_amount: number;
  amount_paid: number;
  balance_amount: number;
  payment_status: "unpaid" | "partially_paid" | "paid";
  online_payment_enabled: boolean;
  /** True only when online payment is on and the rooms are held for payment. */
  payment_required: boolean;
  hold_expires_at: string | null;
  price_breakdown: Quote | null;
  invoice_available: boolean;
  /** Booking summary generated by the server from the saved booking. */
  whatsapp_message: string;
  created_at: string | null;
};

export type BookingRoomLine = {
  room_category_id: number;
  name: string;
  room_type: RoomType | null;
  room_type_label: string | null;
  quantity: number;
  nightly_rate: number;
  nights: number;
  subtotal: number;
};

export type ApiSuccess<T> = {
  success: true;
  message: string;
  data: T;
};

export type ApiError = {
  success: false;
  message: string;
  errors: Record<string, string[]> | object;
};

export type BookingPolicies = {
  check_in_time: string;
  check_out_time: string;
  child_policy_age: number;
  cancellation_days: number;
  cancellation_refund_percent: number;
  missed_ship_refund: boolean;
  advance_percent: number;
  hold_minutes: number;
  online_payment_enabled: boolean;
  missed_ship_policy: string;
};
